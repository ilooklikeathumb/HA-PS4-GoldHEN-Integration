MAC = "aabbccddeeff"
PIN = "13374201"
ACCOUNT = "AAAAAAAAAEI="


class CipherTests(unittest.TestCase):
    def test_cfb128_nist_vector(self):
        # NIST SP 800-38A F.3.13 CFB128-AES128 (also `openssl enc -aes-128-cfb`)
        key = bytes.fromhex("2b7e151628aed2a6abf7158809cf4f3c")
        iv = bytes.fromhex("000102030405060708090a0b0c0d0e0f")
        plain = bytes.fromhex("6bc1bee22e409f96e93d7e117393172aae2d8a571e03ac9c9eb76fac45af8e51")
        cipher = bytes.fromhex("3b3fd92eb72dad20333449f8e83cfb4ac8a64537a0b3a93fcde3cdad9f1ce58b")
        self.assertEqual(rp._aes_cfb(key, iv, plain, decrypt=False), cipher)
        self.assertEqual(rp._aes_cfb(key, iv, cipher, decrypt=True), plain)
        # partial last block (records are not block-aligned)
        self.assertEqual(rp._aes_cfb(key, iv, plain[:21], decrypt=False), cipher[:21])
        self.assertEqual(rp._aes_cfb(key, iv, cipher[:21], decrypt=True), plain[:21])

    def test_iv_ps4(self):
        nonce = bytes.fromhex("3e7e7a825973adab2f694346bd44dab5")
        self.assertEqual(rp.generate_iv(rp._HMAC_KEYS[rp.RP_10], nonce, 0).hex(), "ac489977f92ac55bb9093c33b6113c46")

    def test_pin_seed_ps4(self):
        seed = rp.modern_pin_seed(rp.INIT_KEY_PS4, 78703893, 0x1E)
        self.assertEqual(seed.hex(), "edfc1dc5a2fe2d7f09198575336c1316")

    def test_pin_seed_ps5_table(self):
        seed = rp.modern_pin_seed(ps5.INIT_KEY_PS5, 78703893, 0x1E)
        self.assertEqual(seed.hex(), "e29d644c141b9d617431a56d34cfc17f")

    def test_tables(self):
        self.assertEqual(len(rp.INIT_KEY_PS4), 512)
        self.assertEqual(len(rp.AERO_KEY_PS4), 512)
        self.assertEqual(rp.INIT_KEY_PS4[:4].hex(), "bece5df0")

    def test_full_payload_matches_chiaki_ps5_vector(self):
        """Whole pipeline (preface, nonce placement, seed, IV, record, CFB) — PS5 tables + key, same code path."""
        nonce = bytes.fromhex("1337deadbeefc0ffee42636869616b69")
        tables = rp._ModernTables(ps5.INIT_KEY_PS5, ps5.AERO_KEY_PS5, -0x2D & 0xFF)
        crypto = rp.regist_crypto(PIN, nonce, rp.RP_10, tables=tables,
                                  hmac_key=bytes.fromhex("464687b349ca8ce859c5270f5d7a69d6"))
        payload = rp.build_payload(crypto, ACCOUNT, rp.RP_10)
        expected = (
            "41" * 199 + "67dd36ad47d4c2ce" + "41" * (0x191 - 0xC7 - 8) + "8ed494ee70eba06b" + "41" * (480 - 0x191 - 8)
            + "b444c33edc7eaca50ca55f7988c31ec4fd893b5c64dd7741a324f483ee61919bdfc5b712343be1c66fb6ec0fc6f38bd6c653bd"
            "501115aaa75ed916405b312627fd8a98949dc8b245507cb7ec4fde1bdac6bd449964b3d6cedfc0dd95f39e4e4718c47c23bb45"
            "499830c465"
        )
        self.assertEqual(payload.hex(), expected)

    def test_ps4_payload_shape(self):
        nonce = bytes(range(16))
        crypto = rp.regist_crypto(PIN, nonce, rp.RP_10)
        payload = rp.build_payload(crypto, ACCOUNT, rp.RP_10)
        record = f"Client-Type: {rp.CLIENT_TYPE}\r\nNp-AccountId: {ACCOUNT}\r\n".encode()
        self.assertEqual(len(payload), 480 + len(record))
        self.assertEqual(crypto.decrypt(payload[480:]), record)
        untouched = [i for i in range(480) if not (0xC7 <= i < 0xCF or 0x191 <= i < 0x199)]
        self.assertTrue(all(payload[i] == 0x41 for i in untouched))

    def test_legacy_payload_shape(self):
        nonce = bytes(range(16))
        crypto = rp.regist_crypto(PIN, nonce, rp.RP_9)
        payload = rp.build_payload(crypto, ACCOUNT, rp.RP_9)
        self.assertEqual(crypto.decrypt(payload[480:]), f"Client-Type: Windows\r\nNp-AccountId: {ACCOUNT}\r\n".encode())
        self.assertEqual(crypto.key[4:], rp._LEGACY_AES_KEY[4:])
        self.assertTrue(all(payload[i] == 0x41 for i in range(480) if not 0x11C <= i < 0x12C))


class ParsingTests(unittest.TestCase):
    def test_pin(self):
        for raw in ("13374201", "1337 4201", " 1337-4201 "):
            with self.subTest(raw=raw):
                self.assertEqual(rp.parse_pin(raw), "13374201")
        for raw in ("", "1337420", "133742011", "1337420a"):
            with self.subTest(raw=raw):
                with self.assertRaises(ValueError):
                    rp.parse_pin(raw)

    def test_account_id_forms(self):
        number = 0x0123456789ABCDEF
        b64 = base64.b64encode(number.to_bytes(8, "little")).decode()
        for raw in (b64, f" {b64} ", "0123456789abcdef", "0123456789ABCDEF", "0x0123456789abcdef", str(number)):
            with self.subTest(raw=raw):
                self.assertEqual(rp.parse_account_id(raw), b64)
        self.assertEqual(rp.parse_account_id(ACCOUNT), ACCOUNT)

    def test_account_id_rejected(self):
        for raw in ("", "nope", "AAAA", "AAAAAAAAAAAAAAAG", "0" * 16, "AAAAAAAAAAA=", str(1 << 64), "0123456789abcde"):
            with self.subTest(raw=raw):
                with self.assertRaises(ValueError):
                    rp.parse_account_id(raw)

    def test_rp_version(self):
        self.assertEqual(rp.rp_version_for("11008001"), rp.RP_10)
        self.assertEqual(rp.rp_version_for("12028001"), rp.RP_10)
        self.assertEqual(rp.rp_version_for("08000000"), rp.RP_10)
        self.assertEqual(rp.rp_version_for("07550001"), rp.RP_9)
        self.assertEqual(rp.rp_version_for("05050001"), rp.RP_8)
        self.assertEqual(rp.rp_version_for(None), rp.RP_10)

    def test_registration_body(self):
        body = (
            f"AP-Ssid: x\r\nPS4-RegistKey: {REGIST_KEY.encode().hex()}\r\nRP-KeyType: 2\r\nRP-Key: {RP_KEY.upper()}\r\n"
            f"PS4-Mac: {MAC}\r\nPS4-Nickname: PS4-test\r\n"
        ).encode()
        reg = rp.parse_registration(body)
        self.assertEqual((reg.regist_key, reg.rp_key, reg.mac, reg.nickname, reg.key_type),
                         (REGIST_KEY, RP_KEY, MAC, "PS4-test", "2"))
        self.assertNotIn(REGIST_KEY, repr(reg))
        self.assertNotIn(RP_KEY, repr(reg))

    def test_registration_body_incomplete(self):
        for body in (b"", f"RP-Key: {RP_KEY}\r\nPS4-Mac: {MAC}\r\n".encode(),
                     f"PS4-RegistKey: zz\r\nRP-Key: {RP_KEY}\r\nPS4-Mac: {MAC}\r\n".encode(),
                     f"PS4-RegistKey: {REGIST_KEY.encode().hex()}\r\nRP-Key: 0011\r\nPS4-Mac: {MAC}\r\n".encode()):
            with self.subTest(body=body):
                with self.assertRaises(rp.RegistError) as ctx:
                    rp.parse_registration(body)
                self.assertEqual(ctx.exception.reason, "invalid_response")


def _free_port() -> int:
    """A port free for both TCP and UDP on 127.0.0.1."""
    while True:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as tcp:
            tcp.bind(("127.0.0.1", 0))
            port = tcp.getsockname()[1]
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as udp:
                udp.bind(("127.0.0.1", port))
            return port
        except OSError:
            continue


class FakePS4:
    """DDP on one UDP port; SRC2/RES2 (UDP) + the registration HTTP server (TCP) on another, like port 9295."""

    def __init__(self, *, ddp_code=200, system_version="11008001", answer_search=True, http_code=200, reason=None,
                 nonce=bytes(range(16))):
        self.ddp_code = ddp_code
        self.system_version = system_version
        self.answer_search = answer_search
        self.http_code = http_code
        self.reason = reason
        self.nonce = nonce
        self.requests = []
        self.searches = []

    async def start(self):
        loop = asyncio.get_running_loop()
        fake = self

        class Ddp(asyncio.DatagramProtocol):
            def connection_made(self, transport):
                self.t = transport

            def datagram_received(self, data, addr):
                if data.startswith(b"SRCH"):
                    text = {200: "Ok", 620: "Server Standby"}[fake.ddp_code]
                    self.t.sendto(f"HTTP/1.1 {fake.ddp_code} {text}\nhost-type:PS4\nsystem-version:{fake.system_version}\n"
                                  "host-request-port:997\n".encode(), addr)

        class Search(asyncio.DatagramProtocol):
            def connection_made(self, transport):
                self.t = transport

            def datagram_received(self, data, addr):
                fake.searches.append(data)
                if fake.answer_search and data == b"SRC2\x00":
                    self.t.sendto(b"RES2", addr)

        self.ddp_port = 0
        self.ddp, _ = await loop.create_datagram_endpoint(Ddp, local_addr=("127.0.0.1", 0))
        self.ddp_port = self.ddp.get_extra_info("sockname")[1]
        self.rp_port = _free_port()
        self.search, _ = await loop.create_datagram_endpoint(Search, local_addr=("127.0.0.1", self.rp_port))
        self.http = await asyncio.start_server(self._handle, "127.0.0.1", self.rp_port)
        return self

    async def _handle(self, reader, writer):
        head = await reader.readuntil(b"\r\n\r\n")
        lines = head.decode().split("\r\n")
        headers = {k.lower(): v.strip() for k, _, v in (line.partition(":") for line in lines[1:] if line)}
        body = await reader.readexactly(int(headers["content-length"]))
        self.requests.append((lines[0], headers, body))
        if self.http_code != 200:
            extra = f"RP-Application-Reason: {self.reason}\r\n" if self.reason else ""
            writer.write(f"HTTP/1.1 {self.http_code} Forbidden\r\n{extra}Content-Length: 0\r\n\r\n".encode())
        else:
            version = headers["rp-version"]
            crypto = rp.regist_crypto(PIN, self.nonce, version)
            record = crypto.decrypt(body[480:]).decode()
            assert f"Np-AccountId: {ACCOUNT}" in record, record
            reply = crypto.encrypt(
                f"AP-Name: PS4\r\nPS4-RegistKey: {REGIST_KEY.encode().hex()}\r\nRP-KeyType: 2\r\nRP-Key: {RP_KEY}\r\n"
                f"PS4-Mac: {MAC}\r\nPS4-Nickname: PS4-test\r\n".encode()
            )
            writer.write(f"HTTP/1.1 200 OK\r\nContent-Length: {len(reply)}\r\n\r\n".encode() + reply)
        await writer.drain()
        writer.close()

    def close(self):
        self.ddp.close()
        self.search.close()
        self.http.close()


class EndToEndTests(unittest.TestCase):
    def _register(self, fake, **kwargs):
        async def run():
            await fake.start()
            try:
                return await rp.async_register("127.0.0.1", "1337 4201", ACCOUNT, ddp_port=fake.ddp_port,
                                               rp_port=fake.rp_port, search_timeout=0.6, response_timeout=2,
                                               nonce=fake.nonce, **kwargs)
            finally:
                fake.close()
        return asyncio.run(run())

    def _reason(self, fake):
        with self.assertRaises(rp.RegistError) as ctx:
            self._register(fake)
        return ctx.exception.reason

    def test_pairs(self):
        fake = FakePS4()
        reg = self._register(fake)
        self.assertEqual((reg.regist_key, reg.rp_key, reg.mac, reg.nickname), (REGIST_KEY, RP_KEY, MAC, "PS4-test"))
        line, headers, body = fake.requests[0]
        self.assertEqual(line, "POST /sie/ps4/rp/sess/rgst HTTP/1.1")
        self.assertEqual(headers["rp-version"], "10.0")
        self.assertEqual(headers["user-agent"], "remoteplay Windows")
        self.assertEqual(fake.searches[0], b"SRC2\x00")

    def test_legacy_firmware_path(self):
        fake = FakePS4(system_version="07550001")
        self.assertEqual(self._register(fake).regist_key, REGIST_KEY)
        line, headers, _ = fake.requests[0]
        self.assertEqual(line, "POST /sce/rp/regist HTTP/1.1")
        self.assertEqual(headers["rp-version"], "9.0")

    def test_wrong_pin(self):
        self.assertEqual(self._reason(FakePS4(http_code=403, reason="80108b09")), "wrong_pin")

    def test_invalid_account(self):
        self.assertEqual(self._reason(FakePS4(http_code=403, reason="0x80108B02")), "invalid_account")

    def test_unknown_refusal(self):
        self.assertEqual(self._reason(FakePS4(http_code=403)), "failed")

    def test_resting_console(self):
        fake = FakePS4(ddp_code=620)
        self.assertEqual(self._reason(fake), "resting")
        self.assertEqual(fake.searches, [])

    def test_no_search_reply(self):
        fake = FakePS4(answer_search=False)
        self.assertEqual(self._reason(fake), "no_search_reply")
        self.assertEqual(len(fake.searches), 3)
        self.assertEqual(fake.requests, [])

    def test_no_console(self):
        async def run():
            port = _free_port()
            return await rp.async_register("127.0.0.1", PIN, ACCOUNT, ddp_port=port, rp_port=port)
        with self.assertRaises(rp.RegistError) as ctx:
            asyncio.run(run())
        self.assertEqual(ctx.exception.reason, "no_console")


